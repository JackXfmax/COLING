def clean_情境(s, 下句):
    """剥离 情境 末尾对 下句（含义）的复述，避免字面捷径假阳性。
    原设计：XHY 的 情境 应当是'情境描写'，不应把答案（下句）当包袱甩在句尾。"""
    if 下句 and 下句 in s:
        s = s.replace(下句, "")
    s = re.sub(r"真是?$", "", s.strip("，。 "))
    s = re.sub(r"，\s*真?$", "", s)
    s = s.rstrip("，。 ")
    if s and not s.endswith("。"):
        s += "。"
    return s or "（情境待补）"


