def block_sig(b):
    """从块文本中提取内容签名，用于去重（同一条目无论 ID 如何都只追加一次）。"""
    m = re.search(r"^上句:\s*(.*)$", b, re.M)
    if m:
        n = re.search(r"^下句:\s*(.*)$", b, re.M)
        return "XHY|" + m.group(1).strip() + "|" + (n.group(1).strip() if n else "")
    m = re.search(r"^成语:\s*(.*)$", b, re.M)
    if m:
        return "AID|" + m.group(1).strip()
    m = re.search(r"^农谚:\s*(.*)$", b, re.M)
    if m:
        return "NY|" + m.group(1).strip()
    return ""


def existing_sigs(fname):
    path = os.path.join(DATA, fname)
    if not os.path.exists(path):
        return set()
    txt = open(path, encoding="utf-8").read()
    parts = re.split(r"(?=^id: )", txt, flags=re.M)
    return set(block_sig(p) for p in parts if p.strip())


def append_blocks(fname, blocks):
    """按内容签名去重追加：已存在的条目（无论 ID）跳过，保证可重复运行不重复。"""
    path = os.path.join(DATA, fname)
    have = existing_sigs(fname)
    added = 0
    with open(path, "a", encoding="utf-8") as f:
        for b in blocks:
            s = block_sig(b)
            if s and s in have:
                continue
            f.write("\n" + b)
            have.add(s)
            added += 1
    return added


def render_and_append(rows, render_fn, pre, fname):
    """只渲染真正新增（按内容签名去重）的行，并连续分配 ID，避免留空档。"""
    have = existing_sigs(fname)
    txt = open(os.path.join(DATA, fname), encoding="utf-8").read()
    nums = [int(i.split("-")[1]) for i in re.findall(r"^id: (%s-\d+)" % pre, txt, re.M)]
    nxt = (max(nums) if nums else 0) + 1
    out = []
    for row in rows:
        b = render_fn("%s-%03d" % (pre, nxt), *row)
        s = block_sig(b)
        if s and s in have:
            continue
        if s:
            have.add(s)
        out.append(b)
        nxt += 1
    append_blocks(fname, out)   # append_blocks 内部再校验一次，安全幂等
    return len(out)


def main():
    for pre, rows, render_fn, fname in [
        ("XHY", XHY, render_xhy, "pilot_xhy.md"),
        ("AID", AID, render_aid, "pilot_aid.md"),
        ("NY",  NY,  render_ny,  "pilot_ny.md"),
    ]:
        added = render_and_append(rows, render_fn, pre, fname)
        print("%s 实际新增 %d" % (pre, added))


