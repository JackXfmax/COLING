def render_yy(iid, 原句, 隐藏义, 地区, 等级, 来源, 类型):
    return (
        "id: %s\n" % iid +
        "原句: %s\n" % 原句 +
        "隐藏义: %s\n" % 隐藏义 +
        "类型: %s\n" % 类型 +
        "地区: %s\n" % 地区 +
        "等级: %s\n" % 等级 +
        "来源: %s\n" % 来源 +
        "mem题: 隐语/字谜「%s」的隐藏义（谜底）是什么？\n" % 原句 +
        "mem答案: %s\n" % 隐藏义 +
        "comp题: 隐语/字谜「%s」。它主要运用了下列哪种修辞手法（谜格）？\n" % 原句 +
        "comp选项:\n" +
        "  A. 字面直解（字面义）\n" +
        "  B. %s（正确）\n" % ("谐音双关" if "双关" in 类型 or "谐音" in 类型 else ("离合拆字" if "离合" in 类型 else "隐语藏词")) +
        "  C. 常见误读义（高频义）\n" +
        "  D. 无法确定\n" +
        "comp答案: B\n" +
        "mem干扰: \n"
    )


def block_sig_yy(b):
    m = re.search(r"^原句:\s*(.*)$", b, re.M)
    return "YY|" + (m.group(1).strip() if m else "")


def existing_sigs(fname):
    path = os.path.join(DATA, fname)
    if not os.path.exists(path):
        return set()
    txt = open(path, encoding="utf-8").read()
    parts = re.split(r"(?=^id: )", txt, flags=re.M)
    return set(block_sig_yy(p) for p in parts if p.strip())


def append_blocks(fname, blocks):
    path = os.path.join(DATA, fname)
    have = existing_sigs(fname)
    added = 0
    with open(path, "a", encoding="utf-8") as f:
        for b in blocks:
            s = block_sig_yy(b)
            if s and s in have:
                continue
            f.write("\n" + b)
            have.add(s)
            added += 1
    return added


def render_and_append(rows, 类型, fname):
    have = existing_sigs(fname)
    txt = open(os.path.join(DATA, fname), encoding="utf-8").read()
    nums = [int(i.split("-")[1]) for i in re.findall(r"^id: (YY-\d+)", txt, re.M)]
    nxt = (max(nums) if nums else 0) + 1
    out = []
    for row in rows:
        原句, 隐藏义, 地区, 等级, 来源 = row
        b = render_yy("YY-%03d" % nxt, 原句, 隐藏义, 地区, 等级, 来源, 类型)
        s = block_sig_yy(b)
        if s and s in have:
            continue
        if s:
            have.add(s)
        out.append(b)
        nxt += 1
    return append_blocks(fname, out)


